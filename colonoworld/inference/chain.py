"""Full-procedure generation: a cecum-to-rectum withdrawal generated as a chain of chunks.

The withdrawal through a synthetic whole colon
(:func:`colonoworld.tube.synthetic_colon.build_full_colon`) is split into 189-frame chunks that
share one frame (stride 188). Chunk ``k`` is generated by
:meth:`colonoworld.models.ColonoWorldModel.generate` from

* its first frame: the start frame for the first generated chunk, otherwise the last generated
  frame of chunk ``k - 1`` (kept losslessly as ``chunk_XX_last.npy``);
* the camera poses of the chunk relative to its first frame, with the rays restricted to the
  endoscope field of the synthetic videos;
* the tube rendered along those poses and stored as H.264 (the format of the training tubes);
* per-latent-frame segment ids of the commanded anatomy (output frames 0, 4, 8, ...);
* optional per-chunk conditions (mask classes and special light) from a conditions manifest;
* the seed ``seed + seed_stride * k``.

Frame 0 of every generated chunk is replaced by the exact input frame. The stitched video keeps
all frames of the first chunk and drops the shared first frame of every later chunk.

Conditions manifest (JSON)::

    {"chunks": {"8": "chunk08.npz", "14": {"npz": "chunk14.npz"}}}

Paths are relative to the manifest. Chunks that are not listed use camera and tube only. Each
``.npz`` describes the 189 output frames of its chunk (frame 0 = the hand-off frame):

* ``choice``: JSON string ``{"polyp", "tool", "water", "snare": null | "mask" | "empty"}``
  (``"mask"``: the class mask is given; ``"empty"``: the class is known to be absent);
* ``mask_<class>`` for every ``"mask"`` class: boolean ``(189, H, W)`` or bit-packed along the
  width (``np.packbits(mask, axis=-1)``, ``uint8 (189, H, ceil(W / 8))``);
* optional ``nbi`` / ``nbi_known``: per-frame special light value and known bit (0/1).
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

MASK_CHANNELS: tuple[str, ...] = ("polyp", "tool", "water", "snare")


# ----------------------------------------------------------------------------- media
def read_frames(path: str | Path) -> np.ndarray:
    """Decode a video to ``uint8`` RGB frames ``(T, H, W, 3)`` (PyAV, single thread)."""
    import av

    with av.open(str(path)) as container:
        container.streams.video[0].thread_count = 1
        frames = [
            frame.reformat(format="rgb24", threads=1).to_ndarray()
            for frame in container.decode(video=0)
        ]
    return np.stack(frames)


def read_start_frame(path: str | Path) -> np.ndarray:
    """RGB ``uint8`` start frame from an image file or a ``.npy`` array (H, W, 3)."""
    path = Path(path)
    if path.suffix == ".npy":
        frame = np.load(path, allow_pickle=False)
    else:
        import cv2

        image = cv2.imread(str(path), cv2.IMREAD_COLOR)
        if image is None:
            raise FileNotFoundError(path)
        frame = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
    if frame.ndim != 3 or frame.shape[2] != 3 or frame.dtype != np.uint8:
        raise ValueError("start frame must be uint8 (H, W, 3)")
    return frame


class VideoWriter:
    """Streaming H.264 writer (yuv420p, single thread); frames are appended in batches."""

    def __init__(self, path: str | Path, fps: float = 24, crf: int = 18):
        import av

        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.fps, self.crf = fps, crf
        self.container = av.open(str(self.path), "w", options={"movflags": "+faststart"})
        self.stream = None
        self.count = 0

    def append(self, frames: np.ndarray) -> None:
        import av

        if self.stream is None:
            self.stream = self.container.add_stream("libx264", rate=int(round(self.fps)))
            self.stream.height, self.stream.width = frames.shape[1:3]
            self.stream.pix_fmt = "yuv420p"
            self.stream.codec_context.thread_count = 1
            self.stream.options = {"crf": str(self.crf), "preset": "fast", "threads": "1"}
        for image in frames:
            frame = av.VideoFrame.from_ndarray(np.ascontiguousarray(image), format="rgb24")
            for packet in self.stream.encode(frame.reformat(format="yuv420p", threads=1)):
                self.container.mux(packet)
            self.count += 1

    def close(self) -> None:
        if self.stream is not None:
            for packet in self.stream.encode():
                self.container.mux(packet)
        self.container.close()

    def __enter__(self) -> VideoWriter:
        return self

    def __exit__(self, *exc: object) -> None:
        self.close()


def write_frames(path: str | Path, frames: np.ndarray, fps: float = 24) -> None:
    """Write ``uint8`` RGB frames to an H.264 mp4."""
    with VideoWriter(path, fps) as writer:
        writer.append(frames)


# ----------------------------------------------------------------------------- tube chunks
@dataclass
class FullColonTube:
    """Camera path, per-frame anatomy and tube chunk videos of one synthetic colon.

    ``directory`` holds the layout written by ``scripts/build_full_colon.py --render``:
    ``tube.npz``, ``cameras.npy`` (T, 4, 4 camera-to-world), ``segments.json`` and one
    ``chunk_XX.mp4`` tube video per chunk.
    """

    directory: Path
    cameras: np.ndarray
    labels: list[str]
    ranges: list[tuple[int, int]]

    def chunk_video(self, k: int) -> Path:
        return self.directory / f"chunk_{k:02d}.mp4"

    def chunk_cameras(self, k: int) -> np.ndarray:
        """Poses of chunk ``k`` relative to its first frame."""
        from colonoworld.tube.camera import relative_poses

        start, end = self.ranges[k]
        return relative_poses(self.cameras[start:end])

    def chunk_labels(self, k: int) -> list[str]:
        start, end = self.ranges[k]
        return self.labels[start:end]


def render_chunk(tube: Any, cameras: np.ndarray, intrinsics: Mapping[str, Any]) -> np.ndarray:
    """Render the tube along the (world) cameras of one chunk."""
    from colonoworld.tube.render import render_tube_video

    return render_tube_video(tube, cameras, dict(intrinsics))


def prepare_tube(
    shape: str, shapes_cfg: Mapping[str, Any], directory: str | Path, chunks: list[int]
) -> FullColonTube:
    """Build (or reuse) the synthetic colon of ``shape`` in ``directory`` and render the tube
    videos of ``chunks`` that are not there yet."""
    from colonoworld.tube.render import write_tube_video
    from colonoworld.tube.synthetic_colon import (
        build_full_colon,
        chunk_ranges,
        full_colon_intrinsics,
    )

    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    tube = None
    if not (directory / "cameras.npy").is_file() or not (directory / "segments.json").is_file():
        tube, cameras, segments = build_full_colon(shape, dict(shapes_cfg))
        tube.save(directory / "tube.npz")
        np.save(directory / "cameras.npy", cameras)
        info = dict(shape=shape, frames=len(cameras), chunks=chunk_ranges(len(cameras)))
        (directory / "segments.json").write_text(json.dumps(dict(info, segments=segments)))
    cameras = np.load(directory / "cameras.npy")
    segments = json.loads((directory / "segments.json").read_text())["segments"]
    labels = [""] * len(cameras)
    for run in segments:
        labels[run["start"] : run["end"] + 1] = [run["name"]] * (run["end"] - run["start"] + 1)
    result = FullColonTube(directory, cameras, labels, chunk_ranges(len(cameras)))
    intrinsics = None
    for k in chunks:
        if result.chunk_video(k).is_file():
            continue
        if tube is None:
            from colonoworld.tube import TubeModel

            tube = TubeModel.load(directory / "tube.npz")
        if intrinsics is None:
            intrinsics = full_colon_intrinsics(dict(shapes_cfg))
        start, end = result.ranges[k]
        write_tube_video(result.chunk_video(k), render_chunk(tube, cameras[start:end], intrinsics))
    return result


def latent_field_mask(shapes_cfg: Mapping[str, Any], size: tuple[int, int]) -> np.ndarray:
    """Endoscope field of the synthetic videos on the latent grid (16 px cells).

    A cell is inside when every 8 px sample of the device-field alpha in it is at least 0.5.
    """
    from colonoworld.tube.render import resolve_field_alpha
    from colonoworld.tube.synthetic_colon import full_colon_intrinsics

    alpha = resolve_field_alpha(full_colon_intrinsics(dict(shapes_cfg)), size)
    coarse = (alpha >= 0.5)[::8, ::8]
    h, w = size[0] // 16, size[1] // 16
    return coarse.reshape(h, 2, w, 2).all((1, 3))


# ----------------------------------------------------------------------------- conditions
def read_conditions_manifest(path: str | Path) -> dict[int, Path]:
    """Per-chunk condition files of a manifest: ``{chunk index: npz path}``."""
    path = Path(path)
    chunks = json.loads(path.read_text())["chunks"]
    out = {}
    for key, value in chunks.items():
        file = Path(value["npz"] if isinstance(value, Mapping) else value)
        out[int(key)] = file if file.is_absolute() else path.parent / file
    return out


def load_chunk_conditions(path: str | Path, frames: int, height: int, width: int) -> dict:
    """Read one chunk's conditions: ``choice``, boolean ``masks`` (``"empty"`` classes as all-false
    masks), and ``nbi`` / ``nbi_known`` per-frame arrays or ``None``."""
    with np.load(path, allow_pickle=False) as z:
        choice = json.loads(str(z["choice"]))
        if set(choice) != set(MASK_CHANNELS) or any(
            v not in (None, "mask", "empty") for v in choice.values()
        ):
            raise ValueError(f"{path}: choice must give null/'mask'/'empty' for {MASK_CHANNELS}")
        if choice["snare"] is not None and choice["tool"] is None:
            raise ValueError(f"{path}: a snare channel needs the tool channel")
        masks = {}
        for cls in MASK_CHANNELS:
            if choice[cls] == "mask":
                m = z["mask_" + cls]
                if m.dtype == np.uint8 and m.shape == (frames, height, (width + 7) // 8):
                    m = np.unpackbits(m, axis=-1)[..., :width]
                if m.shape != (frames, height, width):
                    raise ValueError(f"{path}: mask_{cls} must cover ({frames}, {height}, {width})")
                masks[cls] = m.astype(bool)
            elif choice[cls] == "empty":
                masks[cls] = np.zeros((frames, height, width), bool)
        nbi = nbi_known = None
        if "nbi" in z.files:
            nbi = np.asarray(z["nbi"]).astype(bool)
            nbi_known = (
                np.asarray(z["nbi_known"]).astype(bool)
                if "nbi_known" in z.files
                else np.ones(frames, bool)
            )
    return dict(choice=choice, masks=masks, nbi=nbi, nbi_known=nbi_known)


def condition_inputs(
    cond: Mapping[str, Any] | None, frames: int
) -> tuple[np.ndarray | None, np.ndarray | None]:
    """Palette video (``None`` when no class is supplied) and global flags of one chunk."""
    if cond is None:
        return None, None
    from colonoworld.conditions.palette import render_palette_video
    from colonoworld.models.conditions import global_flags

    palette = None
    if any(v is not None for v in cond["choice"].values()):
        palette = render_palette_video(cond["masks"])
    flags = global_flags(
        frames,
        nbi=cond["nbi"],
        nbi_known=cond["nbi_known"],
        choice=cond["choice"],
        masks=cond["masks"],
    )
    return palette, flags


# ----------------------------------------------------------------------------- chain
def chunk_seed(seed: int, stride: int, k: int) -> int:
    """Seed of chunk ``k``."""
    return (int(seed) + int(stride) * int(k)) % 2**32


def chunk_segment_ids(labels: list[str], mode: str) -> np.ndarray:
    """Per-latent-frame segment ids: ``commanded`` anatomy or all ``null``."""
    from colonoworld.models.conditions import SEGMENT_NULL, segment_ids_from_labels

    if mode == "commanded":
        return segment_ids_from_labels(labels)
    if mode == "null":
        return np.full(1 + (len(labels) - 1) // 4, SEGMENT_NULL, np.int64)
    raise ValueError("segment_ids must be 'commanded' or 'null'")


def run_full_procedure(cfg: Mapping[str, Any], model: Any = None) -> Path:
    """Generate a full procedure (or a range of its chunks) as configured in
    ``configs/full_procedure.yaml``.

    Writes to ``output.dir``: ``chunks/chunk_XX.mp4`` (each generated chunk),
    ``chunks/chunk_XX_last.npy`` (its last frame, the next chunk's start frame),
    ``full_procedure.mp4`` (stitched) and ``summary.json``. Returns the output directory.
    """
    from colonoworld.utils.config import load_config

    chain = cfg["chain"]
    video_cfg = cfg["video"]
    frames, height, width = (int(video_cfg[k]) for k in ("frames", "height", "width"))
    fps = float(video_cfg["fps"])
    shapes_cfg = load_config(chain["shapes_config"])
    out = Path(cfg["output"]["dir"])
    (out / "chunks").mkdir(parents=True, exist_ok=True)

    tube_dir = Path(chain.get("tube_dir") or out / "tube")
    probe = prepare_tube(chain["shape"], shapes_cfg, tube_dir, [])
    start = int(chain.get("start_segment") or 0)
    count = chain.get("segments")
    count = len(probe.ranges) - start if count is None else int(count)
    if not (0 <= start and 1 <= count and start + count <= len(probe.ranges)):
        raise ValueError(f"chunks {start}..{start + count - 1} outside 0..{len(probe.ranges) - 1}")
    ks = list(range(start, start + count))
    tube = prepare_tube(chain["shape"], shapes_cfg, tube_dir, ks)

    conditions = {}
    if chain.get("conditions"):
        conditions = read_conditions_manifest(chain["conditions"])
        outside = sorted(set(conditions) - set(ks))
        if outside:
            print(f"conditions for chunks {outside} are outside this run and not used")

    if model is None:
        from colonoworld.models import load_model

        model = load_model(cfg)
    calibration = shapes_cfg["full_colon"]["calibration"]
    field = latent_field_mask(shapes_cfg, (height, width))
    sampling = cfg.get("sampling", {})
    seed, stride = int(chain["seed"]), int(chain["seed_stride"])

    frame = read_start_frame(chain["frame0"])
    if frame.shape != (height, width, 3):
        raise ValueError(f"start frame must be ({height}, {width}, 3)")
    records = []
    with VideoWriter(out / "full_procedure.mp4", fps) as stitched:
        for index, k in enumerate(ks):
            tube_video = read_frames(tube.chunk_video(k))
            if tube_video.shape != (frames, height, width, 3):
                raise ValueError(f"tube chunk {k} must be ({frames}, {height}, {width}, 3)")
            cond = None
            if k in conditions:
                cond = load_chunk_conditions(conditions[k], frames, height, width)
            palette, flags = condition_inputs(cond, frames)
            s = chunk_seed(seed, stride, k)
            video = model.generate(
                frame,
                tube.chunk_cameras(k),
                tube_video,
                cond_mask=palette,
                caption=sampling.get("caption"),
                tube_cfg=sampling.get("tube_cfg"),
                mask_cfg=sampling.get("mask_cfg"),
                guidance=sampling.get("guidance"),
                num_steps=sampling.get("num_steps"),
                seed=s,
                intrinsics=calibration,
                field_mask=field,
                segment_ids=chunk_segment_ids(tube.chunk_labels(k), chain["segment_ids"]),
                mask_choice=None if cond is None else cond["choice"],
                mask_classes=None if cond is None else cond["masks"],
                flags=flags,
            )
            video[0] = frame
            write_frames(out / "chunks" / f"chunk_{k:02d}.mp4", video, fps)
            np.save(out / "chunks" / f"chunk_{k:02d}_last.npy", video[-1])
            stitched.append(video if index == 0 else video[1:])
            records.append(
                dict(
                    chunk=k,
                    seed=s,
                    frames=list(tube.ranges[k]),
                    conditions=None if cond is None else str(conditions[k]),
                    mask=palette is not None,
                    global_flags=flags is not None,
                )
            )
            print(f"chunk {k:02d} done ({index + 1}/{count})", flush=True)
            frame = video[-1].copy()
            del video, tube_video, palette
    summary = dict(
        shape=chain["shape"],
        start_segment=start,
        segments=count,
        frame0=str(chain["frame0"]),
        stitched_frames=frames + (frames - 1) * (count - 1),
        sampling={k: sampling.get(k) for k in ("num_steps", "tube_cfg", "mask_cfg", "guidance")},
        segment_ids=chain["segment_ids"],
        chunks=records,
    )
    (out / "summary.json").write_text(json.dumps(summary, indent=1))
    return out
